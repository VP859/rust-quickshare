// Sessions with a web browser: a link and QR code that a phone or computer
// without Ferry opens to download shared files and send files here.
import { $, close, el, fail, open, toast } from './dom.js';
import { t } from './i18n.js';
import { copyText, invoke } from './tauri.js';

let expiresAt = null;
let timer = null;

function renderExpiry() {
  if (expiresAt === null) { $('web-expires').textContent = ''; return; }
  const left = expiresAt - Date.now();
  $('web-expires').textContent = left > 0 ? t('web_expires', { min: Math.max(1, Math.ceil(left / 60000)) }) : t('web_expired');
}

/** Starts a session sharing `paths` (none: only receiving) and shows its link. */
export async function startWebShare(paths = []) {
  try {
    const info = await invoke('start_web_share', { paths });
    $('web-title').textContent = info.files ? t('web_title_files', { n: info.files }) : t('web_title_receive');
    $('web-qr').innerHTML = info.qr_svg; // generated by the backend (qrcode crate), never user input
    $('web-url').textContent = info.url;
    $('web-firewall').textContent = info.firewall ?? '';
    $('web-firewall').hidden = !info.firewall;
    const others = info.urls.filter(u => u !== info.url);
    $('web-other').replaceChildren(...others.map(u => el('div', { class: 'mono' }, u)));
    $('web-other').hidden = !others.length;
    expiresAt = info.expires_in === null ? null : Date.now() + info.expires_in * 1000;
    renderExpiry();
    clearInterval(timer);
    timer = setInterval(renderExpiry, 15000);
    open('modal-web');
  } catch (e) { fail(e); }
}

$('btn-web-receive').onclick = () => startWebShare([]);
$('btn-web-copy').onclick = () => copyText($('web-url').textContent);
$('btn-web-stop').onclick = async () => {
  try { await invoke('stop_web_share'); } catch (e) { fail(e); return; }
  clearInterval(timer);
  expiresAt = null;
  close('modal-web');
  toast(t('web_stopped'));
};
