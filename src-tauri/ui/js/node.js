// This device's node: its status in the top bar and its TICKET.
import { $, close, fail, open, shortId } from './dom.js';
import { t } from './i18n.js';
import { state } from './state.js';
import { copyText, invoke } from './tauri.js';

export function renderNodeStatus() {
  const { nodeInfo, nodeState } = state;
  $('node-dot').className = 'dot ' + (nodeState === 'ok' ? 'ok' : nodeState === 'bad' ? 'bad' : 'wait');
  $('node-status').textContent = nodeState === 'ok' ? t('node_active', { id: shortId(nodeInfo.node_id) })
    : nodeState === 'bad' ? t('node_unavailable') : t('node_starting');
  $('node-pill').title = nodeInfo?.node_id ?? '';
}

export async function loadNodeInfo() {
  try {
    state.nodeInfo = await invoke('get_node_info');
    state.nodeState = 'ok';
  } catch (e) {
    state.nodeState = 'bad';
    fail(e);
  }
  renderNodeStatus();
}

export function showTicket(title, desc, ticket, svg) {
  $('ticket-title').textContent = title;
  $('ticket-desc').textContent = desc;
  $('ticket-qr').innerHTML = svg; // generated by the backend (qrcode crate), never user input
  $('ticket-text').textContent = ticket;
  open('modal-ticket');
}

$('btn-my-ticket').onclick = async () => {
  if (!state.nodeInfo) await loadNodeInfo();
  const info = state.nodeInfo;
  if (info) showTicket(t('own_ticket_title'), t('own_ticket_desc'), info.ticket, info.qr_svg);
};
$('btn-ticket-copy').onclick = () => copyText($('ticket-text').textContent);
$('btn-ticket-close').onclick = () => close('modal-ticket');
