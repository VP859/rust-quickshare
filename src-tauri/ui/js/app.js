// ---------- Trusted devices ----------
let peers = [];
const online = new Map();
let openMenu = null;
function closeMenu() {
  openMenu?.closest('.list')?.classList.remove('menu-open');
  openMenu?.remove();
  openMenu = null;
}
document.addEventListener('click', closeMenu);

async function refreshPeers() {
  try { peers = await invoke('list_peers'); } catch (e) { fail(e); peers = []; }
  renderPeers();
}

function renderPeers() {
  const box = $('peers');
  $('peers-count').textContent = peers.length;
  closeMenu();
  box.replaceChildren();
  if (!peers.length) {
    box.append(emptyState('shield', t('no_peers')));
    return;
  }
  for (const p of peers) {
    const state = online.get(p.node_id);
    const status = state === true ? t('peer_online') : state === false ? t('peer_offline') : t('peer_checking');
    const label = t('send_to', { name: p.alias });
    const sendBtn = el('button', { class: 'ghost icon', 'aria-label': label, title: label,
      onclick: (e) => { e.stopPropagation(); sendToPeer(p); } }, icon('send', 'sm'));
    const menuBtn = el('button', { class: 'ghost icon', 'aria-label': t('device_options'), title: t('device_options'),
      onclick: (e) => { e.stopPropagation(); showMenu(row, p); } }, icon('more'));
    const row = el('div', { class: 'row clickable device', tabindex: '0', 'data-node': p.node_id, role: 'button', 'aria-label': label,
        onclick: () => sendToPeer(p),
        onkeydown: (e) => { if (e.key === 'Enter' && e.target === row) sendToPeer(p); } },
      el('div', { class: 'avatar' }, initials(p.alias), el('span', { class: dotClass(state) })),
      el('div', { class: 'body' },
        el('div', { class: 'title' }, p.alias),
        el('div', { class: 'sub', title: p.node_id }, status,
          p.auto_accept ? [' · ', el('span', { class: 'tag' }, 'Auto-Accept')] : '',
          p.verified ? [' · ', el('span', { class: 'tag verified', title: t('safety_verified') }, `✓ ${t('verified_tag')}`)] : '')),
      el('div', { class: 'trailing' }, sendBtn, menuBtn));
    box.append(row);
  }
}

async function checkOnline() {
  await Promise.all(peers.map(async (p) => {
    try { online.set(p.node_id, await invoke('peer_online', { nodeId: p.node_id })); }
    catch { online.set(p.node_id, false); }
    renderPeers();
  }));
}

