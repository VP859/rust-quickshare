document.addEventListener('DOMContentLoaded', async () => {
  applyStaticText();
  renderNodeStatus();
  renderNoTransfers();
  renderPeers();
  if (!invoke) { toast(t('no_tauri'), true); return; }
  await loadLanguage();
  applyStaticText();
  renderNodeStatus();
  renderNoTransfers();
  loadAppInfo();
  await listen('transfer', ({ payload }) => renderTransfer(payload));
  await listen('transfer-error', ({ payload }) => fail(payload.message));
  await listen('incoming-offer', ({ payload }) => { offers.push(payload); if (offers.length === 1) showNextOffer(); else $('offer-queue').textContent = t('queued', { n: offers.length - 1 }); });
  await listen('node-error', ({ payload }) => fail(payload));
  await listen('incoming-text', ({ payload }) => { textRequests.push(payload); if (textRequests.length === 1) showNextTextRequest(); else $('text-in-queue').textContent = t('queued', { n: textRequests.length - 1 }); });
  await listen('text-received', ({ payload }) => onTextReceived(payload));
  await listen('request-cancelled', ({ payload }) => {
    for (const [queue, show, expired] of [[offers, showNextOffer, null], [pairRequests, showNextPairRequest, 'pair_expired'], [textRequests, showNextTextRequest, 'text_expired']]) {
      const i = queue.findIndex(r => r.id === payload);
      if (i < 0) continue;
      queue.splice(i, 1);
      if (i === 0) show();
      if (expired) toast(t(expired), true);
    }
  });
  await listen('nearby', ({ payload }) => setNearby(payload));
  await listen('peers-changed', async () => { await refreshPeers(); renderNearby(); });
  // Also emitted by the background pairing after adding a device by TICKET,
  // which has no dialog open yet.
  await listen('pairing-code', ({ payload }) => {
    if (pairingWith !== payload.node_id) {
      pairingWith = payload.node_id;
      $('pairing-title').textContent = t('pairing_with', { name: payload.name });
      open('modal-pairing');
    }
    $('pairing-code').textContent = payload.code;
    $('pairing-status').textContent = t('waiting_confirmation');
  });
  await listen('pair-result', async ({ payload }) => {
    if (pairingWith === payload.node_id) {
      $('pairing-status').textContent = payload.message;
      if (payload.ok) setTimeout(() => close('modal-pairing'), 1500);
    }
    toast(payload.message, !payload.ok);
    await refreshPeers();
    renderNearby();
  });
  await listen('pair-request', ({ payload }) => { pairRequests.push(payload); if (pairRequests.length === 1) showNextPairRequest(); else $('pair-req-queue').textContent = t('queued', { n: pairRequests.length - 1 }); });
  await setupDragDrop();
  await refreshPeers();
  await ensureDeviceName();
  try { setNearby(await invoke('list_nearby')); } catch {}
  await loadNodeInfo();
  await loadNetwork();
  await loadPrivacy();
  checkOnline();
  setInterval(checkOnline, 60000);
  setInterval(updateDiscoveryHint, 5000);
  if (isMobile) checkSharedFiles();
});
