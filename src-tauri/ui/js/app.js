// ---------- Nearby devices and pairing ----------
let nearby = [];
const PLATFORMS = { linux: 'Linux', windows: 'Windows', macos: 'macOS', android: 'Android' };
const platformLabel = (p) => PLATFORMS[p] ?? p;
const platformIcon = (p) => p === 'android' ? 'phone' : 'monitor';
const isTrusted = (id) => peers.some(p => p.node_id === id);

function setNearby(list) {
  nearby = list || [];
  for (const d of nearby) if (isTrusted(d.node_id)) online.set(d.node_id, true);
  renderNearby();
  renderPeers();
}

function renderNearby() {
  const box = $('nearby');
  $('nearby-count').textContent = nearby.length;
  box.replaceChildren();
  updateDiscoveryHint();
  if (!nearby.length) {
    box.append(emptyState('wifi', t('searching_nearby')));
    return;
  }
  for (const d of nearby) {
    const peer = peers.find(p => p.node_id === d.node_id);
    const send = el('button', { onclick: (e) => { e.stopPropagation(); sendToDevice(d.node_id, peer?.alias ?? d.name); } },
      icon('send', 'sm'), el('span', { class: 'label-text' }, t('send_file')));
    const text = el('button', { class: 'ghost icon', title: t('send_text'), 'aria-label': t('send_text'),
      onclick: (e) => { e.stopPropagation(); composeText(d.node_id, peer?.alias ?? d.name); } }, icon('text', 'sm'));
    const trailing = peer
      ? el('div', { class: 'trailing' }, text, send)
      : el('div', { class: 'trailing' }, text, send,
          el('button', { class: 'primary', onclick: (e) => { e.stopPropagation(); pairWith(d); } }, t('pair')));
    box.append(el('div', { class: 'row device', 'data-node': d.node_id },
      el('div', { class: 'avatar' }, icon(platformIcon(d.platform)), el('span', { class: 'dot ok' })),
      el('div', { class: 'body' },
        el('div', { class: 'title' }, d.name),
        el('div', { class: 'sub' }, platformLabel(d.platform), peer ? [' · ', el('span', { class: 'tag' }, t('paired_as', { name: peer.alias }))] : '')),
      trailing));
  }
}

